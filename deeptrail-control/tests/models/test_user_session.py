class TestUserSessionProperties:
    """Tests for UserSession computed properties."""

    def test_is_expired_false_for_future_expiry(self):
        """is_expired should return False when expires_at is in the future."""
        session = UserSession(
            user_id="sarah@acme.com",
            idp_issuer="https://acme.okta.com",
            expires_at=datetime.now(timezone.utc) + timedelta(hours=1),
        )

        assert session.is_expired is False

    def test_is_expired_true_for_past_expiry(self):
        """is_expired should return True when expires_at is in the past."""
        session = UserSession(
            user_id="sarah@acme.com",
            idp_issuer="https://acme.okta.com",
            expires_at=datetime.now(timezone.utc) - timedelta(hours=1),
        )

        assert session.is_expired is True

    def test_is_revoked_false_by_default(self):
        """is_revoked should return False when revoked_at is None."""
        session = UserSession(
            user_id="sarah@acme.com",
            idp_issuer="https://acme.okta.com",
        )

        assert session.is_revoked is False

    def test_is_revoked_true_when_revoked(self):
        """is_revoked should return True when revoked_at is set."""
        session = UserSession(
            user_id="sarah@acme.com",
            idp_issuer="https://acme.okta.com",
            revoked_at=datetime.now(timezone.utc),
        )

        assert session.is_revoked is True

    def test_is_active_true_when_not_expired_and_not_revoked(self):
        """is_active should return True when session is valid."""
        session = UserSession(
            user_id="sarah@acme.com",
            idp_issuer="https://acme.okta.com",
            expires_at=datetime.now(timezone.utc) + timedelta(hours=1),
        )

        assert session.is_active is True

    def test_is_active_false_when_expired(self):
        """is_active should return False when session is expired."""
        session = UserSession(
            user_id="sarah@acme.com",
            idp_issuer="https://acme.okta.com",
            expires_at=datetime.now(timezone.utc) - timedelta(hours=1),
        )

        assert session.is_active is False

    def test_is_active_false_when_revoked(self):
        """is_active should return False when session is revoked."""
        session = UserSession(
            user_id="sarah@acme.com",
            idp_issuer="https://acme.okta.com",
            expires_at=datetime.now(timezone.utc) + timedelta(hours=1),
            revoked_at=datetime.now(timezone.utc),
        )

        assert session.is_active is False



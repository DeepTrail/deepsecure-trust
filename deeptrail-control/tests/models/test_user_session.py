"""Unit tests for the UserSession model."""

import uuid
from datetime import datetime, timedelta, timezone

from app.models.user_session import (
    DEFAULT_SESSION_DURATION_HOURS,
    UserSession,
    generate_session_id,
    get_default_expiry,
)


class TestGenerateSessionId:
    """Tests for the session ID generation function."""

    def test_generates_string(self):
        """Session ID should be a string."""
        session_id = generate_session_id()
        assert isinstance(session_id, str)

    def test_has_correct_prefix(self):
        """Session ID should start with 'usess-' prefix."""
        session_id = generate_session_id()
        assert session_id.startswith("usess-")

    def test_contains_uuid(self):
        """Session ID should contain a valid UUID after the prefix."""
        session_id = generate_session_id()
        uuid_part = session_id.replace("usess-", "")
        # Should not raise ValueError if valid UUID
        uuid.UUID(uuid_part)

    def test_generates_unique_ids(self):
        """Each call should generate a unique session ID."""
        ids = [generate_session_id() for _ in range(100)]
        assert len(set(ids)) == 100


class TestGetDefaultExpiry:
    """Tests for the default expiry calculation."""

    def test_returns_datetime(self):
        """Default expiry should return a datetime."""
        expiry = get_default_expiry()
        assert isinstance(expiry, datetime)

    def test_is_timezone_aware(self):
        """Default expiry should be timezone-aware (UTC)."""
        expiry = get_default_expiry()
        assert expiry.tzinfo is not None
        assert expiry.tzinfo == timezone.utc

    def test_is_8_hours_in_future(self):
        """Default expiry should be approximately 8 hours from now."""
        before = datetime.now(timezone.utc)
        expiry = get_default_expiry()
        after = datetime.now(timezone.utc)

        expected_min = before + timedelta(hours=DEFAULT_SESSION_DURATION_HOURS)
        expected_max = after + timedelta(hours=DEFAULT_SESSION_DURATION_HOURS)

        assert expected_min <= expiry <= expected_max


